function inferCloudFieldType(field: string): string {
  if (/(_ids|supported_|requirements|blockers|actions|steps|refs|entities|scenarios|assumptions|fields|behavior|facts)$/.test(field)) return "array";
  if (/(_at|_date|month|period)$/.test(field)) return "string";
  if (/(amount|budget|price|value|rate|ratio|probability|confidence|count|quantity|hours|cards|context|arr|gmv|revenue|total|reserved|available|impact_)/.test(field)) return "number";
  if (/^(mocked|required_|.*_supported)$/.test(field)) return "boolean";
  return "string";
}

function fieldDescription(resource: string, config: ResourceConfig, field: string): string {
  const label = CLOUD_FIELD_LABELS[field] ?? field;
  const description = CLOUD_FIELD_DESCRIPTIONS[field] ?? `用于${config.label ?? resource}的业务识别、筛选或展示。`;
  return `${label}：${description}`;
}

function mergeFields(fields: string[], extra: string[] = []): string[] {
  return [...new Set([...fields, ...extra])];
}

function applyCloudDictionary(): void {
  for (const [resource, config] of Object.entries(CLOUD_COMMODITY_RESOURCES)) {
    config.description = config.description ?? CLOUD_RESOURCE_DESCRIPTIONS[resource] ?? `${config.label ?? resource}的业务数据。`;
    config.fields = mergeFields(config.fields, CLOUD_RESOURCE_FIELD_EXTENSIONS[resource]);
    config.schema = Object.fromEntries(config.fields.map((field) => [
      field,
      {
        type: inferCloudFieldType(field),
        description: fieldDescription(resource, config, field),
      }
    ]));
  }
}

applyCloudDictionary();

