import type { FieldLabels, ResourceConfig } from "../../resources/types.js";
import { loadJson } from "../../data/load-json.js";

type DataRow = Record<string, unknown>;

function cloudResource(
  file: string,
  fields: string[],
  label: string,
  options: Partial<ResourceConfig> = {},
): ResourceConfig {
  return {
    file: `data/cloud-commodity/${file}`,
    fields,
    domain: "cloud_commodity",
    label,
    defaultLimit: 20,
    ...options,
  };
}

function cloudRow(idField: string, nameField: string, extraFields: string[] = []) {
  return (row: DataRow) => {
    const extras = extraFields
      .map((field) => row[field] == null ? "" : `${CLOUD_FIELD_LABELS[field] ?? field} ${row[field]}`)
      .filter(Boolean)
      .join("，");
    return `- [${row[idField] ?? ""}] ${row[nameField] ?? ""}${extras ? `（${extras}）` : ""}`;
  };
}

async function loadCloudSampleAgentAnswers(): Promise<DataRow[]> {
  const data = await loadJson<Record<string, unknown>>("data/cloud-commodity/cloud_sample_agent_answers.json");
  const rows: DataRow[] = [];
  for (const [sampleGroup, value] of Object.entries(data)) {
    const items = Array.isArray(value) ? value : [value];
    items.forEach((item, index) => {
      if (!item || typeof item !== "object" || Array.isArray(item)) return;
      rows.push({
        sample_id: items.length > 1 ? `${sampleGroup}_${index + 1}` : sampleGroup,
        sample_group: sampleGroup,
        ...(item as DataRow),
      });
    });
  }
  return rows;
}

